local H = dofile("tests/harness.lua")
local passed = 0
local function test(name, fn)
    local ok, err = pcall(fn)
    if not ok then error("FAIL " .. name .. ": " .. tostring(err), 0) end
    passed = passed + 1; print("PASS " .. name)
end
local function eq(actual, expected)
    assert(actual == expected, "expected " .. tostring(expected) .. ", got " .. tostring(actual))
end
local guid1 = "GameObject-0-1-0-0-1731-000001"
local guid2 = "GameObject-0-1-0-0-1731-000002"

test("startup registers documented events and waits for a real observation", function()
    local O, s, e = H.New()
    eq(O.diagnostics.pulses, 0); eq(O.diagnostics.nearbyEvent, true)
    eq(e.SlashCmdList.OREGLOW, O.Command)
    for _, frame in ipairs(s.frames) do
        for event in pairs(frame.events) do assert(not event:find("COMBAT_LOG")) end
    end
end)
test("a live ore target pulses once while it stays nearby", function()
    local O, s = H.New()
    s:Ore(guid1); s:Tick(0.25); eq(O.diagnostics.pulses, 1)
    for _ = 1, 600 do s:Tick(0.25) end
    eq(O.diagnostics.pulses, 1)
end)
test("briefly losing and regaining a node does not repeat the alert", function()
    local O, s = H.New()
    s:Ore(guid1); s:Tick(0.25)
    s.guid = nil; s:Tick(3)
    s:Ore(guid1); s:Tick(0.25)
    eq(O.diagnostics.pulses, 1)
end)
test("two distinct nodes with the same ore name can each alert", function()
    local O, s = H.New()
    s:Ore(guid1); s:Tick(0.25)
    s:Ore(guid2); s:Tick(2.1)
    eq(O.diagnostics.pulses, 2)
end)
test("a burst is throttled and the next nearby node is retried", function()
    local O, s = H.New()
    s:Ore(guid1); s:Tick(0.25)
    s:Ore(guid2); s:Tick(0.25); eq(O.diagnostics.pulses, 1)
    s:Tick(2); eq(O.diagnostics.pulses, 2)
end)
test("an identity can rearm after being absent for more than two minutes", function()
    local O, s = H.New()
    s:Ore(guid1); s:Tick(0.25)
    s.guid = nil; s:Tick(121)
    s:Ore(guid1); s:Tick(0.25)
    eq(O.diagnostics.pulses, 2)
end)
test("NPCs, players, herbs, quest objects and items never count as nearby ore", function()
    local O, s = H.New()
    for _, guid in ipairs({"Player-1-1", "Creature-0-1-0-0-1731-1", "Item-1-1"}) do
        s:Ore(guid); s:Tick(3)
    end
    for _, name in ipairs({"Peacebloom", "Copper Ore", "Mine the Copper Vein", "Copper"}) do
        s:Ore(guid1, name); s:Tick(3)
    end
    eq(O.diagnostics.pulses, 0)
end)
test("Poor Copper Vein is recognized", function()
    local O, s = H.New()
    s:Ore(guid1, "Poor Copper Vein"); s:Tick(0.25)
    eq(O.diagnostics.pulses, 1)
end)
test("the minimap API is never called without a real mouse hover", function()
    local O, s = H.New()
    s.tooltip = {lines = {{leftText = "Copper Vein"}}}
    s:Tick(1); eq(s.calls.tooltip, nil); eq(O.diagnostics.pulses, 0)
end)
test("hovering an ore blip pulses once and a held hover never repeats", function()
    local O, s = H.New()
    s.hover = true
    s.tooltip = {lines = {{leftText = "|cffffd100Copper Vein|r"}}}
    s:Tick(0.25)
    for _ = 1, 200 do s:Tick(0.25) end
    eq(O.diagnostics.pulses, 1); eq(O.diagnostics.lastSource, "hover")
end)
test("short repeated hovers of the same name are suppressed", function()
    local O, s = H.New()
    s.hover = true; s.tooltip = {lines = {{leftText = "Copper Vein x2"}}}; s:Tick(0.25)
    s.hover = false; s:Tick(3)
    s.hover = true; s:Tick(0.25)
    eq(O.diagnostics.pulses, 1)
end)
test("nearby and minimap observations of the same kind do not double-pulse", function()
    local O, s = H.New()
    s.hover = true; s.tooltip = {lines = {{leftText = "Copper Vein"}}}; s:Tick(0.25)
    s:Ore(guid1); s:Tick(3)
    eq(O.diagnostics.pulses, 1)
    s:Tick(15); eq(O.diagnostics.pulses, 1)
end)
test("minimap quest text and herb labels are ignored", function()
    local O, s = H.New()
    s.hover = true
    s.tooltip = {lines = {{leftText = "Peacebloom"}, {leftText = "Collect Copper Ore"}}}
    s:Tick(0.25); eq(O.diagnostics.pulses, 0)
end)
test("secret identity and tooltip values are ignored", function()
    local O, s = H.New()
    local secret = setmetatable({secret = true}, {__tostring = function() error("secret used") end})
    s.guid, s.name = secret, secret
    s.hover, s.tooltip = true, secret
    s:Tick(0.25)
    s.guid = guid1; s.tooltip = {lines = secret}; s:Tick(0.25)
    s.tooltip = {lines = {{leftText = secret}}}; s:Tick(0.25)
    eq(O.diagnostics.pulses, 0)
end)
test("no object identities or minimap tooltips are read in combat", function()
    local O, s = H.New()
    s.combat = true; s.hover = true; s:Ore(guid1); s:Tick(1)
    eq(s.calls.guid, nil); eq(s.calls.name, nil); eq(s.calls.tooltip, nil)
    eq(O.diagnostics.pulses, 0)
end)
test("death and taxi suspend observations", function()
    local O, s = H.New(); s:Ore(guid1)
    s.dead = true; s:Tick(1)
    s.dead, s.taxi = false, true; s:Tick(1)
    eq(s.calls.guid, nil); eq(O.diagnostics.pulses, 0)
