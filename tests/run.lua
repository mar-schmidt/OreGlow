test("corrupt saved settings are normalized", function()
    local O = H.New()
    local db = O.LoadSettings({intensity = 99, duration = -3, enabled = "yes", language = "xx"})
    eq(db.intensity, 0.6); eq(db.duration, 0.5); eq(db.enabled, true); eq(db.language, "en")
    db = O.LoadSettings({intensity = 0/0, duration = math.huge})
    eq(db.intensity, 0.28); eq(db.duration, 1.1)
end)
test("the node cache has a fixed upper bound", function()
    local O = H.New(); local gate = O.NewGate()
    for i = 1, 400 do gate:Nearby("GameObject-" .. i, "Copper Vein", i * 2) end
    local count = 0; for _ in pairs(gate.seen) do count = count + 1 end
    assert(count <= 128)
end)
test("pulse envelope is bounded and contains one peak", function()
    local O = H.New(); local previous = 0
    eq(O.PulseAlpha(0, 1, 0.4), 0); eq(O.PulseAlpha(1, 1, 0.4), 0)
    for i = 1, 100 do
        local alpha = O.PulseAlpha(i / 100, 1, 0.4)
        assert(alpha >= 0 and alpha <= 0.4)
        if i <= 25 then assert(alpha >= previous) else assert(alpha <= previous) end
        previous = alpha
    end
end)
